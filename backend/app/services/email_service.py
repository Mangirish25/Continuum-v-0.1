import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from typing import Optional, Dict, Any
from app.core.config import settings
from app.core.logging import logger

class EmailService:
    def __init__(self, provider: str = settings.EMAIL_PROVIDER):
        self.provider = provider

    async def send_handover_email(
        self,
        recipient_email: str,
        employee_name: str,
        project_name: str,
        handover_package: Dict[str, Any],
        sender_email: str = settings.SENDER_EMAIL
    ) -> bool:
        subject = f"[Continuum Handover] Knowledge Continuity Package for {employee_name} ({project_name})"

        # Format HTML email body
        summary = handover_package.get("summary", "")
        contributions = "".join([f"<li>{c}</li>" for c in handover_package.get("contributions", [])])
        github_work = "".join([f"<li>{g}</li>" for g in handover_package.get("github_work", [])])
        jira = "".join([f"<li>{j}</li>" for j in handover_package.get("jira_responsibilities", [])])
        drive = "".join([f"<li>{d}</li>" for d in handover_package.get("drive_knowledge", [])])
        notion = "".join([f"<li>{n}</li>" for n in handover_package.get("notion_knowledge", [])])
        priorities = "".join([f"<li>{p}</li>" for p in handover_package.get("transfer_priorities", [])])

        successor_info = handover_package.get("recommended_successor")
        successor_html = ""
        if successor_info:
            successor_html = f"""
            <div style="background:#eef2ff; border-left:4px solid #4f46e5; padding:12px; margin:15px 0;">
                <h4 style="margin:0 0 5px 0; color:#3730a3;">AI Recommended Successor</h4>
                <p style="margin:0;"><strong>{successor_info.get('name')}</strong> ({successor_info.get('email')})</p>
                <p style="margin:5px 0 0 0; font-size:0.9em; color:#4338ca;">Rationale: {successor_info.get('reason')}</p>
            </div>
            """

        html_body = f"""
        <!DOCTYPE html>
        <html>
        <head>
            <style>
                body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; color: #1f2937; line-height: 1.6; }}
                .container {{ max-width: 680px; margin: 0 auto; padding: 20px; border: 1px solid #e5e7eb; border-radius: 8px; }}
                .header {{ background: #1e293b; color: white; padding: 15px 20px; border-radius: 6px 6px 0 0; }}
                .section {{ margin-top: 20px; padding-bottom: 15px; border-bottom: 1px solid #f3f4f6; }}
                h3 {{ color: #0f172a; margin-bottom: 8px; }}
                ul {{ padding-left: 20px; }}
                .footer {{ margin-top: 25px; font-size: 0.85em; color: #6b7280; text-align: center; }}
            </style>
        </head>
        <body>
            <div class="container">
                <div class="header">
                    <h2 style="margin:0;">Continuum — Knowledge Continuity Handover</h2>
                    <p style="margin:5px 0 0 0; opacity:0.9;">Employee: {employee_name} | Target Project: {project_name}</p>
                </div>
                
                <div class="section">
                    <h3>Executive Summary</h3>
                    <p>{summary}</p>
                    {successor_html}
                </div>

                <div class="section">
                    <h3>Key Contributions</h3>
                    <ul>{contributions or '<li>Detailed in attached resources</li>'}</ul>
                </div>

                <div class="section">
                    <h3>Repository & Source Work (GitHub)</h3>
                    <ul>{github_work or '<li>No direct repository activity recorded</li>'}</ul>
                </div>

                <div class="section">
                    <h3>Jira Open Tasks & Responsibilities</h3>
                    <ul>{jira or '<li>No open Jira issues pending</li>'}</ul>
                </div>

                <div class="section">
                    <h3>Google Drive & Notion Knowledge</h3>
                    <ul>{drive or notion or '<li>Synchronized resource documents available in Continuum dashboard</li>'}</ul>
                </div>

                <div class="section">
                    <h3>Suggested Transition Priorities</h3>
                    <ol>{priorities or '<li>1. Initial walkthrough 2. Access migration</li>'}</ol>
                </div>

                <div class="footer">
                    <p>Generated by Continuum Enterprise Knowledge Continuity Platform.<br/>Confidential & Admin-Approved Report.</p>
                </div>
            </div>
        </body>
        </html>
        """

        if self.provider == "smtp":
            try:
                msg = MIMEMultipart("alternative")
                msg["Subject"] = subject
                msg["From"] = sender_email
                msg["To"] = recipient_email
                msg.attach(MIMEText(html_body, "html"))

                with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT) as server:
                    if settings.SMTP_USER and settings.SMTP_PASSWORD:
                        server.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
                    server.sendmail(sender_email, [recipient_email], msg.as_string())
                logger.info(f"Handover email sent via SMTP to {recipient_email}")
                return True
            except Exception as e:
                logger.error(f"Failed to send email via SMTP: {e}")
                return False
        else:
            # Console / Mock email output
            logger.info(f"[EMAIL SERVICE - CONSOLE PROvider] Handover Email to {recipient_email}:\nSubject: {subject}\nHTML length: {len(html_body)} bytes")
            return True

email_service = EmailService()
